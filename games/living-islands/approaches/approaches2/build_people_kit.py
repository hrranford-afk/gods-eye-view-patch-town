"""Derive people_kit.js from ../../people_options.html (style 6 builder, unchanged code) by line range, so the figures are the project's own.
Run: python3 build_people_kit.py   (fails loudly if the source layout moved)"""
import os, re
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, '..', '..', 'people_options.html'), encoding='utf8').read().split('\n')
def seg(a, b, must):
    t = '\n'.join(src[a - 1:b]); assert must in t, (a, b, must); return t
parts = [
    seg(43, 53, 'function mulberry32'),
    seg(54, 69, 'const CAST'),
    seg(88, 122, 'function bake'),
    seg(142, 329, 'const P6'),
    seg(511, 534, 'function poseAnim'),
]
head = """/* GENERATED by build_people_kit.py from people_options.html (style 6 'best mix' rig). Do not hand-edit. Requires THREE r128. */
(function(root){'use strict';const TAU=Math.PI*2;
"""
tail = """
/* make one settler: key = woman | man | skip | fish. Returns {root, update(t), height}. Pose is a pure function of t. */
function make(key,t){const c=CAST.find(q=>q.key===key);const R=styled(c,P6,BASEPOSE[key]);const rec={key,R,root:R.root,x:({man:-3.3,woman:-1.1,skip:1.1,fish:3.3})[key]};
  mergePivots(R.root);rec.base=clonePose(BASEPOSE[key]);rec.mode={woman:'carry',man:'hammer',skip:'look',fish:'haul'}[key];rec.home={x:0,z:0};
  rec.update=tt=>{if(rec.mode==='carry'){poseAnim(rec,tt);rec.root.position.set(0,0,0);rec.root.rotation.y=0;}else poseAnim(rec,tt);};rec.update(t===undefined?.4:t);return rec;}
root.PeopleKit={CAST,PAL,make};})(window);
"""
open(os.path.join(here, 'people_kit.js'), 'w', encoding='utf8').write(head + '\n'.join(parts) + tail)
print('people_kit.js written')

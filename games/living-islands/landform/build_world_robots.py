#!/usr/bin/env python3
# landform/build_world_robots.py -- build the live-LOD GLBs of every robot recipe the 12 worlds use (python3 + numpy, no Blender), deduplicated by recipe hash.
#   python3 landform/build_world_robots.py          # reads landform/worlds/seedNNNN/life.json, writes assets/collector/world_robots/
# For each distinct recipe_hash in the robot sites: robot_<hash>_live.glb (blender/robot_radical.py or blender/robot_build.py), robot_<hash>_live.js (the same bytes as base64 in a classic script,
# so that file:// pages load it; a served page fetches the .glb), and index.json (hash, plan, recipe seed, triangles, bytes, sha256, total). Nothing is deleted; the same recipes give the same bytes.
import base64, hashlib, json, os, sys, glob

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, 'blender'))
import robot_recipe as RR       # noqa: E402
import robot_radical as RAD     # noqa: E402
import robot_build as RB        # noqa: E402

OUT = os.path.join(ROOT, 'assets', 'collector', 'world_robots')


def recipe_hash(rec):
    return hashlib.sha256(json.dumps(rec, sort_keys=True, separators=(',', ':')).encode()).hexdigest()[:10]


def main():
    need = {}
    for f in sorted(glob.glob(os.path.join(ROOT, 'landform', 'worlds', 'seed*', 'life.json'))):
        for r in json.load(open(f))['robots']:
            need.setdefault(r['recipe_hash'], (r['recipe_seed'], r['radical'], r['plan']))
    os.makedirs(OUT, exist_ok=True)
    idx = dict(note='live-LOD GLBs of the robot recipes of the 12 worlds (landform/build_world_robots.py)', robots={}, total_bytes=0)
    for h, (seed, radical, plan) in sorted(need.items(), key=lambda kv: (kv[1][2], kv[1][0])):
        rec = RR.robot_recipe_for(seed, radical=radical)
        assert recipe_hash(rec) == h, 'recipe changed since export_life.py ran: %s' % h
        p = os.path.join(OUT, 'robot_%s_live.glb' % h)
        st = RAD.write_radical(rec, p, 'live') if radical else RB.write_robot(rec, p, 'live')
        data = open(p, 'rb').read()
        with open(os.path.join(OUT, 'robot_%s_live.js' % h), 'w') as f:
            f.write("/* generated by landform/build_world_robots.py: live GLB of robot recipe %s (%s, seed %d%s), base64. Do not edit. */\n(window.LI_ROBOT_GLB=window.LI_ROBOT_GLB||{})['%s']='%s';\n"
                    % (h, plan, seed, ', radical' if radical else '', h, base64.b64encode(data).decode()))
        idx['robots'][h] = dict(plan=plan, seed=seed, radical=radical, triangles=st['triangles'], bytes=len(data), sha256=hashlib.sha256(data).hexdigest())
        idx['total_bytes'] += len(data)
        print('%s %-8s seed %3d %7d bytes %5d triangles' % (h, plan, seed, len(data), st['triangles']), flush=True)
    with open(os.path.join(OUT, 'index.json'), 'w') as f:
        json.dump(idx, f, indent=1, sort_keys=True)
    print('%d recipes, %d bytes in total' % (len(need), idx['total_bytes']))


if __name__ == '__main__':
    main()
